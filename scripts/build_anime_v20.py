#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Package Anime Factory V20 standalone HTML and V19 backup for Windows."""
from __future__ import annotations
import argparse
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
V19 = ROOT / "anime-factory" / "v19" / "AI_Anime_Factory_V19.html"
V20DIR = ROOT / "anime-factory" / "v20"
GEN = V20DIR / "build_story_v20.py"
SRC = V20DIR / "story_v20.js"

spec = importlib.util.spec_from_file_location("story_v20_patch", GEN)
builder = importlib.util.module_from_spec(spec)
spec.loader.exec_module(builder)

build_spec = importlib.util.spec_from_file_location("build_legacy_packages", ROOT / "scripts" / "build_releases.py")
build_legacy = importlib.util.module_from_spec(build_spec)
build_spec.loader.exec_module(build_legacy)

README = """AI ANIME FACTORY V20 — STORY / COMBAT CONTINUITY
===============================================
Это развитие подлинного HTML V19, не переписанный с нуля редактор.
Работает как автономный 2D-аниматик без обязательного Ollama и интернета.

КАК ЗАПУСТИТЬ В WINDOWS 10
1. Распакуйте ZIP в новую папку, не запускайте внутри архива.
2. Дважды щёлкните RUN_WINDOWS.bat или откройте
   AI_Anime_Factory_V20_STORY_COMBAT.html в Chrome/Edge.
3. В редакторе откройте вкладку «Сюжет и бой V20».
4. Выберите серию и задайте потерю памяти, ранение, цену призыва,
   улики, последствия, доверие, любовь и режиссёрские заметки.
5. Сохраните журнал серии. Проверка покажет структурные ошибки.
6. «Читаемый бой» перенастроит временные интервалы фаз боя и эффекты,
   не удаляя техники, очки ресурсов и сцены.
7. «Создать четыре кадра PNG» делает лист визуальных кадров.
8. «Скачать Story ZIP + JSON» выгружает канон, QA и проект.
9. Во вкладке «Выпуск / QA» экспортируйте эпизод с кадрами.
   Для MP4 понадобится FFmpeg (описан в экспорте V19).
10. JSON от V19 импортируется через «Импортировать JSON».
    Файлы старых проектов сохраняйте отдельно до проверки совместимости.

БЕЗОПАСНОСТЬ
Не публикуйте лицензионные чужие арты без разрешения.
Не храните ключи API в проектах. Всё работает локально.

СИСТЕМНЫЕ ТРЕБОВАНИЯ
Windows 10 x64, Chrome/Edge; 8 ГБ RAM: рендер 640×360, 6 FPS.
Файлы с PNG могут быть крупными. Делайте резервную копию проекта.

ОГРАНИЧЕНИЯ
Это 2D-процедурный аниматик с простыми моделями, а не полноценный
профессиональный 3D-аниме фильм или нейронный генератор видео.
Автоматические проверки канона — эвристика; история требует редактора.
Анимация, озвучивание и рендер ещё требуют ручной проверки на ноутбуке.
"""

RUN = '@echo off\r\nsetlocal\r\ncd /d "%~dp0"\r\nstart "" "AI_Anime_Factory_V20_STORY_COMBAT.html"\r\n'
PROVENANCE = "V19 preserved exactly as source; new V20 is generated by build_story_v20.py from that HTML and story_v20.js. No historical browser release is overwritten.\n"


def build(out):
    source = V19.read_bytes()
    extension = SRC.read_text(encoding="utf-8")
    text = builder.patch(source.decode("utf-8"), extension)
    files = {
        "AI_Anime_Factory_V20_STORY_COMBAT.html": text.encode("utf-8"),
        "backup/AI_Anime_Factory_V19_ORIGINAL.html": source,
        "README_RU.txt": README.encode("utf-8"),
        "RUN_WINDOWS.bat": RUN.encode("utf-8"),
        "SOURCE_PROVENANCE.txt": PROVENANCE.encode("utf-8"),
        "source/story_v20.js": extension.encode("utf-8"),
        "source/build_story_v20.py": GEN.read_bytes()
    }
    out = Path(out).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    build_legacy.make_zip(out, files)
    with __import__("zipfile").ZipFile(out) as z:
        assert z.read("backup/AI_Anime_Factory_V19_ORIGINAL.html") == source
        assert len(z.read("AI_Anime_Factory_V20_STORY_COMBAT.html")) > len(source)
        assert z.testzip() is None
    print("V20 STORY COMBAT ZIP PASS:", out, out.stat().st_size)


def main():
    arg = argparse.ArgumentParser()
    arg.add_argument("--out", default=str(ROOT / "dist" / "AI_ANIME_FACTORY_V20_STORY_COMBAT_WINDOWS.zip"))
    arg.add_argument("--selftest", action="store_true")
    opts = arg.parse_args()
    if opts.selftest:
        builder.selftest()
        return
    build(opts.out)


if __name__ == "__main__":
    main()
