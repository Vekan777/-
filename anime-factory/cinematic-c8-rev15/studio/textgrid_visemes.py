"""Validate real MFA TextGrid intervals and derive candidate viseme timing.

This only runs on supplied TextGrid generated by actual acoustic alignment. Does not
invent timings from letters or mark a voice performance professionally accepted.
"""
from __future__ import annotations
import argparse
import json
import re
import wave
from pathlib import Path

PHONE_VISEMES = {
    'a':'A','aː':'A','ɑ':'A','æ':'A','ɐ':'A','ə':'A','ʌ':'A',
    'e':'E','ɛ':'E','ɪ':'I','i':'I','ɨ':'I','ɯ':'U',
    'o':'O','ɔ':'O','ʊ':'U','u':'U',
    'p':'MBP','b':'MBP','m':'MBP',
    'f':'FV','v':'FV','w':'FV',
    'ʃ':'SH','ʂ':'SH','ʒ':'SH','ʐ':'SH','ɕ':'SH','t͡ɕ':'SH',
    's':'SZ','z':'SZ','t͡s':'SZ',
    'l':'L','ɫ':'L',
    't':'REST','d':'REST','k':'REST','g':'REST','n':'REST','r':'REST',
    'j':'REST','h':'REST','x':'REST','ɡ':'REST','ɲ':'REST','ɾ':'REST',
    'sil':'REST','sp':'REST','spn':'REST','':'REST','<eps>':'REST'
}


def parse_phone_tier(text):
    # Standard long TextGrid: locate tier by `name = "phones"` then parse intervals.
    segments=re.split(r'(?=\s*item \[\d+\]:)',text)
    tier=None
    for item in segments:
        if re.search(r'\bname\s*=\s*"(phones|phone)"',item,re.I):
            tier=item;break
    if tier is None:raise ValueError('PHONE_TIER_MISSING')
    out=[]
    for match in re.finditer(r'intervals\s*\[\d+\]:\s*xmin\s*=\s*([0-9.]+)\s*xmax\s*=\s*([0-9.]+)\s*text\s*=\s*"([^"]*)"',tier):
        out.append({'start':float(match.group(1)),'end':float(match.group(2)),
                    'phone':match.group(3).strip()})
    return out


def audit_textgrid(textgrid,wav):
    textgrid=Path(textgrid);wav=Path(wav)
    problems=[]
    if not textgrid.is_file():problems.append('MISSING_TEXTGRID')
    if not wav.is_file():problems.append('MISSING_WAV')
    if problems:return {'status':'BLOCKED_NOT_ALIGNED','errors':problems,'visemes':[]}
    try:
        with wave.open(str(wav),'rb') as f:
            duration=f.getnframes()/f.getframerate()
        phones=parse_phone_tier(textgrid.read_text(encoding='utf-8'))
    except (ValueError,ZeroDivisionError,wave.Error,UnicodeError) as e:
        return {'status':'BLOCKED_NOT_ALIGNED','errors':[str(e)],'visemes':[]}
    if not phones:problems.append('EMPTY_PHONE_TIER')
    previous_end=0
    out=[];unknown=[]
    for p in phones:
        if p['start']<previous_end-0.001 or p['end']<=p['start'] or p['start']<0:
            problems.append('OVERLAPPING_OR_NEGATIVE_PHONE_INTERVAL')
        if p['start']>previous_end+.10:
            problems.append('UNEXPLAINED_PHONE_TIMELINE_GAP')
        previous_end=p['end']
        symbol=p['phone'].lower()
        viseme=PHONE_VISEMES.get(symbol)
        if viseme is None:
            unknown.append(symbol)
            viseme='UNMAPPED_REQUIRES_REVIEW'
        out.append({'start_s':p['start'],'end_s':p['end'],'phone':p['phone'],'viseme':viseme})
    if abs(previous_end-duration)>.20:problems.append('WAV_TEXTGRID_DURATION_MISMATCH')
    if len(unknown)/max(1,len(phones))>.20:problems.append('MANY_UNMAPPED_RUSSIAN_PHONES')
    if not any(p['viseme'] not in ('REST','UNMAPPED_REQUIRES_REVIEW') for p in out):
        problems.append('NO_IDENTIFIABLE_ARTICULATION')
    return {'status':'BLOCKED_NOT_ALIGNED' if problems else 'PHONE_TIMING_STRUCTURALLY_CHECKED_NEEDS_VISUAL_REVIEW',
        'errors':list(dict.fromkeys(problems)),'duration_s':duration,'phones_count':len(phones),
        'unmapped_phone_symbols':sorted(set(unknown)),
        'visemes':out,'studio_lipsync_approved':False,
        'note':'Valid interval structure does not prove actor timing, intelligibility, good voice or correct Blender shape mapping.'}


def main():
    a=argparse.ArgumentParser()
    a.add_argument('textgrid',type=Path);a.add_argument('wav',type=Path)
    a.add_argument('--output',type=Path,default=Path('output/REV15_VISIMES_REVIEW.json'))
    args=a.parse_args()
    result=audit_textgrid(args.textgrid,args.wav)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({k:v for k,v in result.items() if k!='visemes'},ensure_ascii=False,indent=2))

if __name__=='__main__':main()
